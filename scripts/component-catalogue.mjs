// B-31: the component catalogue, docs/components.md: which composable is which design file, what
// draws it in the engine, which item built it, and how many cells, references and goldens hold it.
//
//   node scripts/component-catalogue.mjs           rewrite the generated part of docs/components.md
//   node scripts/component-catalogue.mjs --check   fail if it is stale, or the map names what is not there
//
// A hand-written catalogue keeps listing what was renamed and stops listing what was added, and both
// look correct. So the one hand-kept part is the map below, and every name in it is held to the
// sources: the design file must be in reference/design-system, the composable public in toon-core,
// the engine renderer a method of toon-engine.js, the item a file in docs/backlog — done when the
// composable exists, not done when it does not. And every public composable of toon-core must be in
// the map, under its design file or among the library's own (`OWN`), or the check fails: a component
// nobody can find is what the catalogue exists to prevent. The counts are read from the files.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DESIGN = join(ROOT, 'reference/design-system');
const SOURCES = join(ROOT, 'toon-core/src/commonMain/kotlin');
const SNAPSHOTS = join(ROOT, 'toon-core/src/desktopTest/snapshots');
const FRAMES = join(ROOT, 'toon-core/src/desktopTest/resources/engine-goldens/components.json');
const DESKTOP = join(ROOT, 'reference/desktop');
const DESKTOP_FRAMES = join(ROOT, 'toon-core/src/desktopTest/resources/engine-goldens/desktop.json');
const BACKLOG = join(ROOT, 'docs/backlog');
const CATALOGUE = join(ROOT, 'docs/components.md');
const BEGIN = '<!-- BEGIN CATALOGUE - generated by scripts/component-catalogue.mjs, do not edit by hand -->';
const END = '<!-- END CATALOGUE -->';

