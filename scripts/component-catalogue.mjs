// Public composables beyond a design file's own, under it.
const ALSO = { Snackbar: ['ToonSnackbarHost'], Tabs: ['rememberToonTabsState'], BottomSheet: ['ToonBottomSheetBox'] };
// The library's own public composables, which no design file draws, with the item that made each.
const OWN = {
  ToonTheme: ['the theme provider: tokens, fonts, reduce motion, the idle budget', 'B-08'],
  rememberToonIdleSlot: ['a slot of the idle budget, for a component that breathes', 'B-08'],
  rememberToonPressState: ['the press machine, for a component of the caller\'s own', 'B-10'],
  ToonFxHost: ['the FX layer that draws the effects events fire', 'B-12'],
  ToonStage: ['the stage: the theme colour and the gouache tile', 'B-13'],
  ToonCardList: ['a column of cards: the 40 ms cascade and the close-up after a dismiss, as the Core page\'s `cardStack`', 'B-46'],
  ToonTransitionHost: ['the screen transitions of the v1 page: push, scene change, hole in the wall', 'B-44'],
  ToonPullToRefreshBox: ['pull-to-refresh over content: the content pulled down, the band in the gap above it', 'B-64'],
  ToonText: ['a consumer\'s own text in a step of the type scale, its Cyrillic in the theme\'s backing faces', 'B-82'],
};

const problems = [];
const engine = readFileSync(join(DESIGN, 'toon-engine.js'), 'utf8');
const itemFiles = readdirSync(BACKLOG).filter((f) => /^B-\d+-.*\.md$/.test(f));
const item = (id) => {
  const f = itemFiles.find((n) => n.startsWith(`${id}-`));
  if (!f) { problems.push(`${id}: no such item in docs/backlog`); return { file: null, status: null }; }
  return { file: f, status: /^status:\s*(\S+)/m.exec(readFileSync(join(BACKLOG, f), 'utf8'))?.[1] };
};

// Every public composable in toon-core's common sources: a `public fun` that `@Composable`, written
// short or qualified, precedes among its annotations, on its line or the lines above.
const kotlin = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? kotlin(join(dir, e.name)) : e.name.endsWith('.kt') ? [join(dir, e.name)] : []);
const composables = new Map();
for (const file of kotlin(SOURCES)) {
  const text = readFileSync(file, 'utf8');
  for (const m of text.matchAll(/@(?:androidx\.compose\.runtime\.)?Composable\b(?:\s*@[^\n]*)*\s*public fun (?:<[^>]*>\s*)?(\w+)\s*\(/g)) composables.set(m[1], file.slice(ROOT.length + 1));
}

const designFiles = readdirSync(DESIGN).filter((f) => /^Toon\w+\.dc\.html$/.test(f)).map((f) => f.slice(4, -8));
for (const d of designFiles) if (!MAP[d]) problems.push(`Toon${d}.dc.html: a design file the catalogue does not map`);
for (const d of Object.keys(MAP)) if (!designFiles.includes(d)) problems.push(`${d}: mapped, but reference/design-system has no Toon${d}.dc.html`);

const frames = JSON.parse(readFileSync(FRAMES, 'utf8'));
const count = (dir, group) => existsSync(dir) ? readdirSync(dir).filter((f) => f.startsWith(`${group}_`) && f.endsWith('.png')).length : 0;
const listed = new Set([...Object.keys(OWN), ...Object.values(ALSO).flat()]);
const rows = [];
for (const d of Object.keys(MAP).sort()) {
  const e = MAP[d];
  for (const fn of e.engine) if (!new RegExp(`^ {4}${fn}\\(`, 'm').test(engine)) problems.push(`${d}: the engine has no \`${fn}\``);
  const it = item(e.item);
  if (e.composable) {
    listed.add(e.composable);
    if (!composables.has(e.composable)) problems.push(`${d}: \`${e.composable}\` is not a public composable in toon-core`);
    if (it.status && it.status !== 'done') problems.push(`${d}: built, but ${e.item} is ${it.status}`);
  } else if (it.status === 'done') problems.push(`${d}: ${e.item} is done, but no composable is mapped`);
  for (const a of ALSO[d] ?? []) if (!composables.has(a)) problems.push(`${d}: \`${a}\` is not a public composable in toon-core`);
  const g = e.group;
  const cells = g && frames[g] ? Object.keys(frames[g]).length : 0;
  const names = e.composable ? [`\`${e.composable}\``, ...(ALSO[d] ?? []).map((a) => `\`${a}\``)].join(', ') : '— not built';
  const src = e.composable && composables.get(e.composable) ? `[${composables.get(e.composable).split('/').pop()}](../${composables.get(e.composable)})` : '';
  rows.push(`| [Toon${d}](../reference/design-system/Toon${d}.dc.html) | ${names} | ${src} | ${e.engine.map((f) => `\`${f}\``).join(', ')} | [${e.item}](backlog/${it.file}) | ${cells || ''} | ${g ? count(join(SNAPSHOTS, 'design'), g) : ''} | ${g ? count(SNAPSHOTS, g) : ''} |`);
}
for (const [name, [, id]] of Object.entries(OWN)) {
  if (!composables.has(name)) problems.push(`\`${name}\` is listed as the library's own, but is not a public composable`);
  item(id);
}

const desktopEngine = readFileSync(join(DESKTOP, 'desktop-engine.js'), 'utf8');
const desktopFiles = readdirSync(DESKTOP).filter((f) => /^Toon\w+\.dc\.html$/.test(f)).map((f) => f.slice(4, -8));
for (const d of desktopFiles) if (!DESKTOP_MAP[d]) problems.push(`desktop Toon${d}.dc.html: a design file the catalogue does not map`);
for (const d of Object.keys(DESKTOP_MAP)) if (!desktopFiles.includes(d)) problems.push(`${d}: mapped, but reference/desktop has no Toon${d}.dc.html`);
const desktopFrames = JSON.parse(readFileSync(DESKTOP_FRAMES, 'utf8'));
const desktopRows = [];
for (const d of Object.keys(DESKTOP_MAP).sort()) {
  const e = DESKTOP_MAP[d];
  for (const fn of e.engine) if (!new RegExp(`P\\.${fn} = function`).test(desktopEngine)) problems.push(`${d}: the desktop extension has no \`${fn}\``);
  const it = item(e.item);
  if (e.composable) {
    listed.add(e.composable);
    if (!composables.has(e.composable)) problems.push(`${d}: \`${e.composable}\` is not a public composable in toon-core`);
    if (it.status && it.status !== 'done') problems.push(`${d}: built, but ${e.item} is ${it.status}`);
  } else if (it.status === 'done') problems.push(`${d}: ${e.item} is done, but no composable is mapped`);
  const cells = desktopFrames[e.group] ? Object.keys(desktopFrames[e.group]).length : 0;
  const src = e.composable && composables.get(e.composable) ? `[${composables.get(e.composable).split('/').pop()}](../${composables.get(e.composable)})` : '';
  desktopRows.push(`| [Toon${d}](../reference/desktop/Toon${d}.dc.html) | ${e.composable ? `\`${e.composable}\`` : '— not built'} | ${src} | ${e.engine.map((f) => `\`${f}\``).join(', ')} | [${e.item}](backlog/${it.file}) | ${cells || ''} |`);
}
for (const [name] of composables) if (!listed.has(name)) problems.push(`\`${name}\` is a public composable the catalogue does not list`);

const own = Object.entries(OWN).map(([name, [what, id]]) => `| \`${name}\` | [${composables.get(name)?.split('/').pop() ?? ''}](../${composables.get(name) ?? ''}) | ${what} | [${id}](backlog/${item(id).file}) |`);
const built = Object.values(MAP).filter((e) => e.composable).length;
const desktopBuilt = Object.values(DESKTOP_MAP).filter((e) => e.composable).length;
const block = [
  BEGIN,
  '',
  `${built} of ${Object.keys(MAP).length} design files are built.`,
  '',
  '| Design file | Composable | Source | Engine | Item | Frame cells | References | Goldens |',
  '|---|---|---|---|---|---|---|---|',
  ...rows,
  '',
  `The desktop set, from reference/desktop (stage 5): ${desktopBuilt} of ${Object.keys(DESKTOP_MAP).length} built. Its frames are in \`desktop.json\`; the project has no spec pages, so no Chrome references or goldens are drawn from it.`,
  '',
  '| Design file | Composable | Source | Extension | Item | Frame cells |',
  '|---|---|---|---|---|---|',
  ...desktopRows,
  '',
  'The library\'s own, which no design file draws:',
  '',
  '| Composable | Source | What it is | Item |',
  '|---|---|---|---|',
  ...own,
  '',
  END,
].join('\n');

const text = readFileSync(CATALOGUE, 'utf8');
const i = text.indexOf(BEGIN);
const j = text.indexOf(END);
if (i < 0 || j < 0) problems.push('docs/components.md has no catalogue markers');
const fresh = i >= 0 && j >= 0 ? text.slice(0, i) + block + text.slice(j + END.length) : text;
if (process.argv.includes('--check')) {
  if (fresh !== text) problems.push('docs/components.md is stale: run `make fix`');
  if (problems.length) { console.error(`component catalogue:\n  ${problems.join('\n  ')}`); process.exit(1); }
  console.log(`component catalogue matches: ${built} of ${Object.keys(MAP).length} design files built`);
} else {
  if (problems.length) { console.error(`component catalogue:\n  ${problems.join('\n  ')}`); process.exit(1); }
  writeFileSync(CATALOGUE, fresh);
  console.log(`docs/components.md written: ${built} of ${Object.keys(MAP).length} design files built`);
}
