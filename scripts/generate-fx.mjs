// B-12: write the FX parity fixtures from the FX page's frame strips (scripts/fx-cells.mjs).
//
//   node scripts/generate-fx.mjs           write FxParityFixtures.kt
//   node scripts/generate-fx.mjs --check   fail if it differs, or if the page no longer says what
//                                          scripts/fx-cells.mjs read from it
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FX_CELLS, missingPageText } from './fx-cells.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'toon-core/src/desktopTest/kotlin/io/github/youndie/toon/parity/FxParityFixtures.kt');
const TOKENS = { il: 'inkGouacheLight', in: 'inkGouacheNight', bc: 'brightCel' };

const kt = `// GENERATED by scripts/generate-fx.mjs from scripts/fx-cells.mjs (B-12). Do not edit: run
// \`make fx\`, and \`make check\` fails while this file is stale.
package io.github.youndie.toon.parity

import androidx.compose.foundation.Canvas
import androidx.compose.foundation.background
import androidx.compose.foundation.layout.size
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.drawscope.DrawScope
import androidx.compose.ui.unit.dp
import io.github.youndie.toon.draw.ToonRadii
import io.github.youndie.toon.fx.drawToonDust
import io.github.youndie.toon.fx.drawToonFlash
import io.github.youndie.toon.fx.drawToonHole
import io.github.youndie.toon.fx.drawToonIris
import io.github.youndie.toon.fx.drawToonSpeed
import io.github.youndie.toon.fx.drawToonStars
import io.github.youndie.toon.fx.drawToonSweat
import io.github.youndie.toon.fx.drawToonVibe
import io.github.youndie.toon.fx.toonIrisAt
import io.github.youndie.toon.fx.toonShake
import io.github.youndie.toon.tokens.ToonColors
import io.github.youndie.toon.tokens.ToonTokens
import io.github.youndie.toon.tokens.brightCel
import io.github.youndie.toon.tokens.inkGouacheLight
import io.github.youndie.toon.tokens.inkGouacheNight
import io.github.youndie.viddik.annotations.ViddikScreenshot

// The FX page's frame strips against the engine's effects drawn in Chrome: each effect alone on its
// theme's stage, with the page's arguments at the strip's timestamp.

@Composable
private fun FxCell(
    tokens: ToonTokens,
    width: Int,
    height: Int,
    draw: DrawScope.(c: ToonColors) -> Unit,
) {
    Canvas(Modifier.size(width.dp, height.dp).background(tokens.colors.stage)) { draw(tokens.colors) }
}
${FX_CELLS.map(c => `
@ViddikScreenshot(group = "${c.group}", name = "${c.name}", width = ${c.w}, height = ${c.h})
@Composable
fun Fx${c.name.replaceAll('_', '')}() =
    FxCell(${TOKENS[c.theme]}, ${c.w}, ${c.h}) { c ->
        ${c.kotlin}
    }
`).join('')}`;

const check = process.argv.includes('--check');
if (missingPageText.length) { console.error(`the FX page no longer says:\n  ${missingPageText.join('\n  ')}`); process.exit(1); }
if (check) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== kt) { console.error('stale: FxParityFixtures.kt - run make fx'); process.exit(1); }
  console.log(`${FX_CELLS.length} FX fixtures match the FX page`);
} else {
  writeFileSync(out, kt);
  console.log(`${FX_CELLS.length} FX fixtures written`);
}
